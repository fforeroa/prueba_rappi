COPY INTO GROUPS_TOPICS_RAW FROM @MEETUP_STAGE/groups_topics.csv.gz FILE_FORMAT = (FORMAT_NAME = 'csv_meetup_format') ON_ERROR = 'CONTINUE' FORCE=TRUE;
COPY INTO MEMBERS_RAW FROM @MEETUP_STAGE/members.csv.gz FILE_FORMAT = (FORMAT_NAME = 'csv_meetup_format') ON_ERROR = 'CONTINUE' FORCE=TRUE;
COPY INTO MEMBERS_TOPICS_RAW FROM @MEETUP_STAGE/members_topics.csv.gz FILE_FORMAT = (FORMAT_NAME = 'csv_meetup_format') ON_ERROR = 'CONTINUE' FORCE=TRUE;
